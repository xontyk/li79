SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

-- ---------------------------------------------------------------------
-- Администраторы
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admins (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    full_name     VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status        ENUM('pending', 'approved', 'rejected') NOT NULL DEFAULT 'pending',
    created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- Ученики-призёры олимпиад
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS olympiad_winners (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    year       SMALLINT UNSIGNED NOT NULL,
    full_name  VARCHAR(255) NOT NULL,
    subject    VARCHAR(255) NOT NULL,
    quote      TEXT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    KEY idx_year (year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- Учителя
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS teachers (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    full_name  VARCHAR(255) NOT NULL,
    subject    VARCHAR(255) NOT NULL,
    photo_path VARCHAR(500) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- Страницы сайта (простая CMS)
-- protected = 1  -> страницу нельзя удалить из админ-панели (Главная, Контакты)
-- nav_order      -> порядок пункта в меню; у собственных страниц, добавленных
--                    администратором, ставится автоматически в конец списка
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pages (
    id               INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    slug             VARCHAR(191) NOT NULL,
    title            VARCHAR(255) NOT NULL,
    content          MEDIUMTEXT NULL,
    meta_description VARCHAR(500) NULL,
    protected        TINYINT(1) NOT NULL DEFAULT 0,
    nav_order        INT NOT NULL DEFAULT 100,
    updated_at       DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_slug (slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ---------------------------------------------------------------------
-- Сообщения с формы обратной связи (страница «Контакты»)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS contact_messages (
    id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    contact    VARCHAR(255) NOT NULL,
    message    TEXT NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET FOREIGN_KEY_CHECKS = 1;

